export function isSupportedLanguage(value: string | null | undefined): value is AppLanguage {
  return !!value && (APP_LANGUAGES as readonly string[]).includes(value);
}

export function resolveLanguage(value: string | null | undefined): AppLanguage {
  if (isSupportedLanguage(value)) return value;
  return FALLBACK_LANGUAGE;
}

export function translate(language: string | null | undefined, key: string): string {
  const resolved = resolveLanguage(language);
  return TRANSLATIONS[resolved][key] || TRANSLATIONS[FALLBACK_LANGUAGE][key] || key;
}

export function getLanguageLabel(language: AppLanguage): string {
  return LANGUAGE_LABELS[language];
}
